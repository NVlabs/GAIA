def sha256_of(path):
    h = hashlib.sha256()
    with open(path, "rb") as fp:
        for chunk in iter(lambda: fp.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def load_obj_counts(path):
    """Minimal OBJ reader: returns (verts, uvs, faces_verts_idx, faces_uv_idx) as lists."""
    verts, uvs, fv, ft = [], [], [], []
    with open(path, errors="replace") as fp:
        for line in fp:
            tok = line.split()
            if not tok:
                continue
            if tok[0] == "v":
                verts.append(tuple(float(x) for x in tok[1:4]))
            elif tok[0] == "vt":
                uvs.append(tuple(float(x) for x in tok[1:3]))
            elif tok[0] == "f":
                vi, ti = [], []
                for corner in tok[1:]:
                    part = corner.split("/")
                    vi.append(int(part[0]) - 1)
                    ti.append(int(part[1]) - 1 if len(part) > 1 and part[1] else -1)
                fv.append(tuple(vi))
                ft.append(tuple(ti))
    return verts, uvs, fv, ft


class Report:
    def __init__(self):
        self.errors, self.warnings = [], []

    def ok(self, msg):
        print(f"    ok       {msg}")

    def warn(self, msg):
        print(f"    WARN     {msg}")
        self.warnings.append(msg)

    def fail(self, msg):
        print(f"    FAIL     {msg}")
        self.errors.append(msg)


def check_hashes(root, rep):
    print("Files and hashes")
    for rel, (want_sha, want_size, strict) in DOWNLOADED.items():
        path = os.path.join(root, rel)
        if not os.path.isfile(path):
            if rel == BUILD_MESH:
                # Build-time input only; nothing loads it at runtime. Absent is fine, but it is
                # needed again to regenerate the runtime mesh.
                rep.warn(f"{rel} is absent -- fine at runtime (build-time input only), but "
                         f"re-run setup_assets.sh before regenerating {RUNTIME_MESH}")
            else:
                rep.fail(f"{rel} is missing -- run setup_assets.sh")
            continue
        size = os.path.getsize(path)
        got = sha256_of(path)
        if got == want_sha:
            rep.ok(rel)
        elif rel == "head_template.obj" and got == WRONG_HEAD_TEMPLATE_SHA256:
            rep.fail(f"{rel} is the standard 9976-face FLAME head (SMIRK's head_template.obj / "
                     f"FlashAvatar's head_template_mesh.obj). It must be FlashAvatar's "
                     f"flame/FlameMesh.obj. This exact mix-up crashed training. Re-run setup_assets.sh.")
        elif strict:
            rep.fail(f"{rel} sha256 mismatch (got {got[:16]}..., size {size} vs {want_size})")
        else:
            rep.warn(f"{rel} sha256 differs from the reference build (got {got[:16]}..., "
                     f"size {size} vs {want_size}) -- expected if regenerated on a different "
                     f"device; structural/numeric checks below are authoritative")


def check_meshes(root, rep):
    print("Mesh topology")
    close = os.path.join(root, RUNTIME_MESH)
    head = os.path.join(root, BUILD_MESH)
    if not os.path.isfile(close):
        rep.fail(f"cannot check topology: {RUNTIME_MESH} is missing")
        return None

    cv, cu, cfv, cft = load_obj_counts(close)

    meshes = [(RUNTIME_MESH, (cv, cu, cfv))]
    if os.path.isfile(head):
        hv, hu, hfv, hft = load_obj_counts(head)
        meshes.append((BUILD_MESH, (hv, hu, hfv)))

    for name, (v, u, fv) in meshes:
        if (len(v), len(u), len(fv)) == (EXPECTED_VERTS, EXPECTED_UVS, EXPECTED_FACES):
            rep.ok(f"{name}: {len(v)} verts / {len(u)} uvs / {len(fv)} faces")
        else:
            rep.fail(f"{name}: got {len(v)} verts / {len(u)} uvs / {len(fv)} faces, "
                     f"expected {EXPECTED_VERTS}/{EXPECTED_UVS}/{EXPECTED_FACES}. "
                     f"A {MOUTH_FACE_START}-face mesh here means the mouth-seal faces are "
                     f"absent and training will fail with a CUDA device-side assert.")

    # Only meaningful while the build-time mesh is still around: it is what the runtime mesh's
    # topology/UVs were generated from, so a divergence means the runtime mesh is stale.
    if os.path.isfile(head):
        if hfv == cfv and hft == cft:
            rep.ok(f"{RUNTIME_MESH} topology matches its source {BUILD_MESH}")
        else:
            rep.fail(f"{RUNTIME_MESH} topology differs from its source {BUILD_MESH} -- "
                     f"regenerate with make_close_mouth_mesh.py")

    max_idx = max((i for f in cfv for i in f), default=-1)
    if max_idx < EXPECTED_VERTS:
        rep.ok(f"face indices in range (max vertex index {max_idx} < {EXPECTED_VERTS})")
    else:
        rep.fail(f"face vertex index {max_idx} >= {EXPECTED_VERTS}")

    return cv


def check_numeric(root, close_verts, rep):
    """Re-derive the close-mouth vertices from FLAME and compare. Needs torch + FLAME2020."""
    print("Numeric re-derivation of flame_uv_close_mouth.obj")
    if close_verts is None:
        rep.fail("skipped: mesh could not be loaded")
        return
    try:
        import json

        import numpy as np
        import torch

        gaia_root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
        if gaia_root not in sys.path:
            sys.path.insert(0, gaia_root)
        from flame.FLAME import FLAMEAssets, load_flame

        from make_close_mouth_mesh import build_close_mouth_vertices
    except Exception as exc:  # noqa: BLE001
        rep.warn(f"skipped (dependencies unavailable): {exc}")
        return

    device = "cuda:0" if torch.cuda.is_available() else "cpu"
    assets = FLAMEAssets(root)
    flame = load_flame(asset_dir=root, device=device)
    with open(assets.flame_to_canonical_params_path) as fp:
        params = json.load(fp)
    derived = build_close_mouth_vertices(flame, params, device)[0].detach().cpu().numpy()

    diff = np.abs(derived - np.asarray(close_verts, dtype=np.float32)).max()
    if diff < 1e-6:
        rep.ok(f"vertices match FLAME forward + canonical alignment (max|d| = {diff:.3e})")
    else:
        rep.fail(f"vertices do NOT match FLAME forward + canonical alignment (max|d| = {diff:.3e}); "
                 f"regenerate with make_close_mouth_mesh.py")


def check_uv_masks(root, rep):
    print("UV region masks (generated by make_uv_masks.py, not downloaded)")
    missing = [m for m in UV_MASKS if not os.path.isfile(os.path.join(root, m))]
    if missing:
        rep.fail(f"{len(missing)} of {len(UV_MASKS)} masks missing (e.g. {missing[0]}). "
                 f"Training loads these. Generate them: python make_uv_masks.py")
        return
    bad = [m for m, want in sorted(UV_MASKS.items())
           if sha256_of(os.path.join(root, m)) != want]
    if bad:
        rep.fail(f"{len(bad)} of {len(UV_MASKS)} masks differ from the pinned hashes "
                 f"(e.g. {bad[0]}); regenerate with make_uv_masks.py")
    else:
        rep.ok(f"all {len(UV_MASKS)} masks present and byte-identical to the pinned hashes")


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--asset-dir", default=os.path.dirname(os.path.abspath(__file__)))
    parser.add_argument("--numeric", action="store_true",
                        help="also re-derive the close-mouth mesh from FLAME (needs torch)")
    args = parser.parse_args()

    root = args.asset_dir
    print(f"Verifying FLAME assets in {root}\n")
    rep = Report()
    check_hashes(root, rep)
    close_verts = check_meshes(root, rep)
    if args.numeric:
        check_numeric(root, close_verts, rep)
    check_uv_masks(root, rep)

    print()
    if rep.errors:
        print(f"FAILED: {len(rep.errors)} error(s), {len(rep.warnings)} warning(s)")
        return 1
    print(f"All checks passed ({len(rep.warnings)} warning(s)).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
