"""
Verify the FLAME asset directory. Read-only: this script never downloads or writes anything.

    python gaia/flame/assets/verify_assets.py            # structural + hash checks
    python gaia/flame/assets/verify_assets.py --numeric  # also re-derive the close-mouth mesh

Why this exists: the two template meshes look interchangeable but are not. Shipping the
standard 9976-face FLAME head as ``head_template.obj`` crashed training with an opaque
``CUDA error: device-side assert triggered`` -- the mouth-seal faces (index >= 9976) indexed
past the end of the face table. The structural checks below catch that on the CPU, before any
CUDA work, with a message that says what is actually wrong.

Hash policy:
  * downloaded files are pinned exactly (sha256) -- a mismatch is an ERROR;
  * ``flame_uv_close_mouth.obj`` is *generated* (float math), so its sha256 is recorded as
    "expected" only -- a mismatch is a WARNING, and correctness is decided by the structural
    and (with --numeric) numeric checks instead.
"""

