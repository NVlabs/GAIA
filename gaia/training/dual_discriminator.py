@persistence.persistent_class
class DualDiscriminator(torch.nn.Module):
    def __init__(self,
        c_dim,                          # Conditioning label (C) dimensionality.
        img_resolution,                 # Input resolution.
        img_channels,                   # Number of input color channels.
        architecture        = 'resnet', # Architecture: 'orig', 'skip', 'resnet'.
        channel_base        = 32768,    # Overall multiplier for the number of channels.
        channel_max         = 512,      # Maximum number of channels in any layer.
        num_fp16_res        = 4,        # Use FP16 for the N highest resolutions.
        conv_clamp          = 256,      # Clamp the output of convolution layers to +-X, None = disable clamping.
        cmap_dim            = None,     # Dimensionality of mapped conditioning label, None = default.
        disc_c_noise        = 0,        # Corrupt camera parameters with X std dev of noise before disc. pose conditioning.
        block_kwargs        = {},       # Arguments for DiscriminatorBlock.
        mapping_kwargs      = {},       # Arguments for MappingNetwork.
        epilogue_kwargs     = {},       # Arguments for DiscriminatorEpilogue.
        pretrained_resolution = None,
        use_new_layer = False,
        use_uv_render_disc = False,
        only_noise_exp = False,
        use_dual_discrimination = False,
        shape_cond_disc=False
    ):
        super().__init__()

        self.use_new_layer = use_new_layer
        self.use_dual_discrimination = use_dual_discrimination
        self.use_uv_render_disc = use_uv_render_disc
        self.only_noise_exp = only_noise_exp
        if self.use_dual_discrimination or self.use_uv_render_disc:
            img_channels *= 2
        self.shape_cond_disc = shape_cond_disc

        if self.shape_cond_disc:
            c_dim = 325
        self.c_dim = c_dim
        self.img_resolution = img_resolution
        self.pretrained_resolution = pretrained_resolution
        self.img_resolution_log2 = int(np.log2(img_resolution))
        self.img_channels = img_channels
        self.block_resolutions = [2 ** i for i in range(self.img_resolution_log2, 2, -1)]
        channels_dict = {res: min(channel_base // res, channel_max) for res in self.block_resolutions + [4]}
        fp16_resolution = max(2 ** (self.img_resolution_log2 + 1 - num_fp16_res), 8)

        if cmap_dim is None:
            cmap_dim = channels_dict[4]
        if c_dim == 0:
            cmap_dim = 0

        common_kwargs = dict(img_channels=img_channels, conv_clamp=conv_clamp)
        cur_layer_idx = 0

        for res in self.block_resolutions:
            is_new_layer = self.pretrained_resolution is not None and res > self.pretrained_resolution and self.use_new_layer
            in_channels = channels_dict[res] if res < img_resolution and (
                        self.pretrained_resolution is None or res != self.pretrained_resolution) else 0

            #in_channels = channels_dict[res] if res < img_resolution else 0
            tmp_channels = channels_dict[res]
            out_channels = channels_dict[res // 2]
            use_fp16 = (res >= fp16_resolution)
            block_architecture = 'skip' if is_new_layer else architecture
            block = DiscriminatorBlock(in_channels, tmp_channels, out_channels, resolution=res,
                first_layer_idx=cur_layer_idx, use_fp16=use_fp16, architecture=block_architecture, **block_kwargs, **common_kwargs)
            if is_new_layer:
                block.conv1.weight.data.zero_()
            setattr(self, f'b{res}', block)
            cur_layer_idx += block.num_layers
        if c_dim > 0:
            self.mapping = MappingNetwork(z_dim=0, c_dim=c_dim, w_dim=cmap_dim, num_ws=None, w_avg_beta=None, **mapping_kwargs)
        self.b4 = DiscriminatorEpilogue(channels_dict[4], cmap_dim=cmap_dim, resolution=4, **epilogue_kwargs, **common_kwargs)
        self.register_buffer('resample_filter', upfirdn2d.setup_filter([1,3,3,1]))
        self.disc_c_noise = disc_c_noise

    def forward(self, img, c, update_emas=False, alpha_new_layers: float = 1, **block_kwargs):

        if self.shape_cond_disc:
            c = c[:, :325]

        if self.use_dual_discrimination:
            if img['image_raw'].shape[-1] != img['image'].shape[-1]:
                image_raw = filtered_resizing(img['image_raw'], size=img['image'].shape[-1], f=self.resample_filter)
            else:
                image_raw = img['image_raw']
            img = torch.cat([img['image'], image_raw], 1)
        else:
            if self.use_uv_render_disc:
                img = torch.cat([img['image'], img['uv_render']], 1)
            else:
                img = img['image']

        _ = update_emas # unused
        x = None
        for res in self.block_resolutions:
            block = getattr(self, f'b{res}')
            if self.pretrained_resolution is not None and res > self.pretrained_resolution:
                # Smoothly blend in outputs of newly added layers (that are not trained yet)
                x, img = block(x, img, **block_kwargs)
                x = alpha_new_layers * x
            else:
                x, img = block(x, img, **block_kwargs)

        cmap = None
        if self.c_dim > 0:
            if self.disc_c_noise > 0:
                if self.only_noise_exp:
                    c[:, 25:] = c[:, 25:] + torch.randn_like(c[:, 25:]) * c[:, 25:].std(0) * self.disc_c_noise
                else:
                    c += torch.randn_like(c) * c.std(0) * self.disc_c_noise
            cmap = self.mapping(None, c)
        x = self.b4(x, img, cmap)
        return x

    def extra_repr(self):
        return f'c_dim={self.c_dim:d}, img_resolution={self.img_resolution:d}, img_channels={self.img_channels:d}'