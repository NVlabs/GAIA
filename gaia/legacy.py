# Key added by the (internal) release-checkpoint build to mark a stripped
# release checkpoint. Its presence is what `--flame-source auto` keys off.
RELEASE_KEY = '_gaia_release'

FLAME_SOURCE_CHOICES = ('auto', 'checkpoint', 'assets')


def is_release_pkl(data):
    """True if `data` came from a stripped release checkpoint."""
    return isinstance(data, dict) and RELEASE_KEY in data


# Files a rehydrated FLAME is built from, with the sha256 pinned in
# flame/assets/verify_assets.py. Rehydration moves the correctness of the
# rendered result onto the user's own asset download, so a silent mismatch here
# would silently produce a different model. Checked, not assumed.
_FLAME_ASSET_SHA256 = {
    "FLAME2020/generic_model.pkl":
        "efcd14cc4a69f3a3d9af8ded80146b5b6b50df3bd74cf69108213b144eba725b",
    "landmark_embedding.npy":
        "8095348eeafce5a02f6bd8765146307f9567a3f03b316d788a2e47336d667954",
    "l_eyelid.npy":
        "fa50997166c2f884fbfc577d99fe8707966763fc3d83a1870bb786df6cc9410d",
    "r_eyelid.npy":
        "dd78776fed765be4468889dd7d5b54b4bf61c8efbb2869b5b91409ce798aad8d",
    "mediapipe_landmark_embedding/mediapipe_landmark_embedding.npz":
        "8863363013fc6fe3752d4318ea02a1784970200616a54b785920cdd0568816fc",
}

# The runtime mesh is float-generated by make_close_mouth_mesh.py, so its hash is
# device-dependent (~1 ULP). Warn on a mismatch, never fail.
_FLAME_ASSET_SHA256_SOFT = {
    "flame_uv_close_mouth.obj":
        "413ed9d8ed321cd06fe5c979aa9b097e84a05fc99ce5e2c8b20fca4b9595005d",
}


def _sha256_of(path):
    import hashlib
    h = hashlib.sha256()
    with open(path, 'rb') as fp:
        for chunk in iter(lambda: fp.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def verify_flame_assets(asset_dir='flame/assets', verbose=True):
    """Check the assets a rehydrated FLAME is built from. Raises on a hard mismatch."""
    import os
    missing, wrong, soft = [], [], []
    for rel, want in _FLAME_ASSET_SHA256.items():
        path = os.path.join(asset_dir, rel)
        if not os.path.isfile(path):
            missing.append(rel)
        elif _sha256_of(path) != want:
            wrong.append(rel)
    for rel, want in _FLAME_ASSET_SHA256_SOFT.items():
        path = os.path.join(asset_dir, rel)
        if os.path.isfile(path) and _sha256_of(path) != want:
            soft.append(rel)

    if missing:
        raise FileNotFoundError(
            'Cannot rehydrate FLAME -- missing asset(s): %s\n'
            'This checkpoint ships without FLAME model data, which is licensed by Max Planck '
            'and not redistributed with GAIA. Download it first:\n'
            '    cd gaia/flame/assets && bash setup_assets.sh' % ', '.join(missing))
    if wrong:
        raise ValueError(
            'Cannot rehydrate FLAME -- sha256 mismatch on: %s\n'
            'These must be the exact files the released model was trained with, or the '
            'rehydrated model will differ from the published one. Re-run\n'
            '    cd gaia/flame/assets && bash setup_assets.sh && python verify_assets.py --numeric'
            % ', '.join(wrong))
    if soft and verbose:
        print('[flame] note: %s differs from the reference build. It is float-generated, so a '
              '~1 ULP difference across devices is expected; run verify_assets.py --numeric if '
              'results look wrong.' % ', '.join(soft))
    if verbose:
        print('[flame] assets verified (%d files) in %s' % (len(_FLAME_ASSET_SHA256), asset_dir))


def rehydrate_flame(data, device='cpu', verbose=True):
    """Rebuild the FLAME submodule of every generator in `data` from local assets.

    Release checkpoints ship without FLAME because it is Max Planck licensed
    data we do not redistribute. The tensors are constants -- a fresh
    `load_flame()` reproduces all 24 of them bit-exactly -- so this is lossless.

    Rebuilds the module rather than loading a state_dict: four of FLAME's
    buffers (face_uvcoords, faces, verts_uvs, textures_idx) are registered
    `persistent=False` and so are absent from state_dict() entirely.
    """
    from flame.FLAME import load_flame

    verify_flame_assets(verbose=verbose)

    for key in ('G', 'G_ema'):
        module = data.get(key)
        if module is None:
            continue
        try:
            # A separate instance per generator, mirroring how training's
            # deepcopy produced independent copies.
            module.flame = load_flame(device=device)
        except FileNotFoundError as err:
            raise FileNotFoundError(
                f'Cannot rehydrate FLAME for {key}: {err}\n'
                'This checkpoint ships without FLAME model data, which is licensed by '
                'Max Planck and not redistributed with GAIA. Download it first:\n'
                '    cd gaia/flame/assets && bash setup_assets.sh'
            ) from err
        if verbose:
            print(f'[flame] {key}: rehydrated from assets')


def _apply_flame_source(data, flame_source, device, verbose=True):
    """Resolve the requested FLAME source against what the checkpoint contains."""
    if flame_source not in FLAME_SOURCE_CHOICES:
        raise ValueError(f'flame_source must be one of {FLAME_SOURCE_CHOICES}, got {flame_source!r}')

    stripped = is_release_pkl(data)

    if flame_source == 'checkpoint':
        if stripped:
            raise ValueError(
                'flame-source=checkpoint was requested, but this is a stripped release '
                'checkpoint that carries no FLAME data. Use --flame-source=auto (the default) '
                'to rehydrate it from gaia/flame/assets/.'
            )
        if verbose:
            print('[flame] using the FLAME embedded in the checkpoint')
        return

    if flame_source == 'assets' or stripped:
        rehydrate_flame(data, device=device, verbose=verbose)
        return

    if verbose:
        print('[flame] using the FLAME embedded in the checkpoint')


def load_network_pkl(f, force_fp16=False, flame_source='auto', device='cpu'):
    try:
        data = _LegacyUnpickler(f).load()
    except (ImportError, AttributeError) as exc:
        # A checkpoint predating the gaia_utils refactor fails here in one of two ways, both
        # opaque about the real cause:
        #   ImportError    -- torch_utils.persistence rebuilds each class by exec'ing the module
        #                     source frozen into the pickle, and that source imports modules this
        #                     tree no longer has (e.g. training.networks_stylegan2_styleunet).
        #   AttributeError -- pickle resolves the GaussianModel activation functions by qualified
        #                     name during .load(); pre-refactor pickles name them in
        #                     scene.gaussian_model, which is pristine upstream and does not define
        #                     them. Observed as: Can't get attribute
        #                     'build_covariance_from_scaling_rotation' on scene.gaussian_model.
        raise RuntimeError(
            f'failed to unpickle {getattr(f, "name", "checkpoint")}: {exc}\n'
            'This looks like a pre-release checkpoint. Only the published release checkpoint '
            'is supported; support for pre-refactor pickles was retired along with the '
            'compatibility layer.'
        ) from exc

    # Legacy TensorFlow pickle => convert.
    if isinstance(data, tuple) and len(data) == 3 and all(isinstance(net, _TFNetworkStub) for net in data):
        tf_G, tf_D, tf_Gs = data
        G = convert_tf_generator(tf_G)
        D = convert_tf_discriminator(tf_D)
        G_ema = convert_tf_generator(tf_Gs)
        data = dict(G=G, D=D, G_ema=G_ema)

    # Add missing fields.
    if 'training_set_kwargs' not in data:
        data['training_set_kwargs'] = None
    if 'augment_pipe' not in data:
        data['augment_pipe'] = None

    # Validate contents.
    assert isinstance(data['G'], torch.nn.Module)
    assert isinstance(data['D'], torch.nn.Module)
    assert isinstance(data['G_ema'], torch.nn.Module)
    assert isinstance(data['training_set_kwargs'], (dict, type(None)))
    assert isinstance(data['augment_pipe'], (torch.nn.Module, type(None)))
    if 'D2' in data.keys():
        assert isinstance(data['D2'], torch.nn.Module)

    # Restore FLAME if this is a stripped release checkpoint (or if explicitly
    # asked to). A normal training snapshot is untouched by default.
    _apply_flame_source(data, flame_source, device)

    # Force FP16.
    if force_fp16:
        for key in ['G', 'D', 'G_ema']:
            old = data[key]
            kwargs = copy.deepcopy(old.init_kwargs)
            fp16_kwargs = kwargs.get('synthesis_kwargs', kwargs)
            fp16_kwargs.num_fp16_res = 4
            fp16_kwargs.conv_clamp = 256
            if kwargs != old.init_kwargs:
                new = type(old)(**kwargs).eval().requires_grad_(False)
                misc.copy_params_and_buffers(old, new, require_all=True)
                data[key] = new
    return data

